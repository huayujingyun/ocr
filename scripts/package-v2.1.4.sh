## Troubleshooting

### Python Command Not Found
If \`python\` command doesn't work, use \`py\` command instead:
\`\`\`
py --version
\`\`\`

### Port Already in Use
If port 5000 or 8000 is already in use, change the port number:
\`\`\`
# Backend: Change --port 8000 to --port 8001
# Frontend: Change -p 5000 to -p 5001
\`\`\`

### OCR Not Working
1. Make sure backend is running on port 8000
2. Check browser console (F12) for errors
3. Verify template is set before uploading images
4. Check backend logs for error messages

## Support

For detailed documentation, see:
- README.md - Complete project documentation
- docs/BACKEND_API_FIX.md - Backend API fix details
- docs/WINDOWS_DEPLOY.md - Windows deployment guide

## Version History

