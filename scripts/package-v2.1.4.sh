#!/bin/bash

# OCR Card Recognizer - Windows Deployment Package v2.1.4
# This script creates a deployment package for Windows with all necessary files
# Including the backend API fix

set -e

# Colors for output
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo -e "${GREEN}========================================${NC}"
echo -e "${GREEN}  OCR Card Recognizer - Packaging v2.1.4${NC}"
echo -e "${GREEN}========================================${NC}"
echo ""

# Package info
PACKAGE_NAME="ocr-card-recognizer-windows-v2.1.4"
PACKAGE_VERSION="v2.1.4"
PACKAGE_DATE=$(date +%Y-%m-%d)

# Clean up old package
echo "Cleaning up old package..."
rm -rf ${PACKAGE_NAME}
rm -f ${PACKAGE_NAME}.tar.gz

# Create package directory
echo "Creating package directory..."
mkdir -p ${PACKAGE_NAME}

# Copy essential project files
echo "Copying project files..."

# Frontend files
echo "  - Frontend configuration..."
cp -r src ${PACKAGE_NAME}/
cp package.json ${PACKAGE_NAME}/
cp tsconfig.json ${PACKAGE_NAME}/
cp tailwind.config.ts ${PACKAGE_NAME}/
cp postcss.config.mjs ${PACKAGE_NAME}/
cp next.config.ts ${PACKAGE_NAME}/
cp pnpm-lock.yaml ${PACKAGE_NAME}/
cp .coze ${PACKAGE_NAME}/
cp -r .cozeproj ${PACKAGE_NAME}/

# Backend files
echo "  - Backend files..."
cp -r backend ${PACKAGE_NAME}/
# Remove Python cache
find ${PACKAGE_NAME}/backend -type d -name "__pycache__" -exec rm -rf {} + 2>/dev/null || true

# Documentation
echo "  - Documentation files..."
mkdir -p ${PACKAGE_NAME}/docs
cp README.md ${PACKAGE_NAME}/
cp BACKEND_API_FIX.md ${PACKAGE_NAME}/docs/ 2>/dev/null || true
cp QUICKSTART.md ${PACKAGE_NAME}/docs/ 2>/dev/null || true
cp WINDOWS_DEPLOY.md ${PACKAGE_NAME}/docs/ 2>/dev/null || true

# Create version info file
cat > ${PACKAGE_NAME}/VERSION.txt << EOF
OCR Card Recognizer - Windows Deployment Package
================================================

Version: ${PACKAGE_VERSION}
Release Date: ${PACKAGE_DATE}

What's New:
- Fixed backend API route mismatch issue
- Added /api/ocr endpoint for frontend compatibility
- Fixed template-based image cropping
- Fixed OCR recognition failures
- All previous fixes (Python env, Tailwind CSS, env vars)

Requirements:
- Windows 10/11
- Python 3.12
- Node.js 18+ with pnpm
- PaddleOCR (will be installed automatically)

Quick Start:
1. Install Python dependencies: cd backend && py -m pip install -r requirements.txt
2. Install frontend dependencies: pnpm install
3. Build frontend: pnpm run build
4. Start backend: cd backend && py -m uvicorn main:app --host 0.0.0.0 --port 8000
5. Start frontend: pnpm run start
6. Access: http://localhost:5000

For detailed instructions, see README.md and docs/ directory.

Generated by: Coze Coding Expert
EOF

# Create README for package
cat > ${PACKAGE_NAME}/README_PACKAGING.md << EOF
# OCR Card Recognizer - Windows Deployment Package v${PACKAGE_VERSION}

## Package Contents

This package contains the complete source code for OCR Card Recognizer, optimized for Windows deployment.

### Directory Structure

\`\`\`
ocr-card-recognizer-windows-v${PACKAGE_VERSION}/
├── src/                      # Frontend source code
│   ├── app/                  # Next.js app directory
│   ├── components/           # React components
│   └── lib/                  # Utility functions
├── backend/                  # Backend source code
│   ├── main.py              # FastAPI application
│   ├── ocr_service.py       # OCR service
│   └── requirements.txt     # Python dependencies
├── docs/                     # Documentation
│   ├── BACKEND_API_FIX.md   # Backend API fix documentation
│   └── ...
├── package.json             # Node.js dependencies
├── tsconfig.json            # TypeScript config
├── tailwind.config.ts       # Tailwind CSS config
├── .coze                    # Coze CLI config
└── VERSION.txt              # Version information
\`\`\`

## Quick Installation

### Prerequisites

1. **Python 3.12**: Download from https://www.python.org/downloads/
   - During installation, check "Add Python to PATH"
   - Verify installation: \`py --version\`

2. **Node.js 18+**: Download from https://nodejs.org/
   - Install pnpm: \`npm install -g pnpm\`

3. **Git** (optional): For version control

### Installation Steps

1. **Extract the package**
   \`\`\`
   Right-click the .tar.gz file and "Extract Here"
   \`\`\`

2. **Install backend dependencies**
   \`\`\`
   cd backend
   py -m pip install -r requirements.txt
   \`\`\`

3. **Install frontend dependencies**
   \`\`\`
   cd ..
   pnpm install
   \`\`\`

4. **Build the frontend**
   \`\`\`
   pnpm run build
   \`\`\`

### Running the Application

**Terminal 1 - Start Backend:**
\`\`\`
cd backend
py -m uvicorn main:app --host 0.0.0.0 --port 8000
\`\`\`

**Terminal 2 - Start Frontend:**
\`\`\`
cd ..
pnpm run start
\`\`\`

**Open Browser:**
\`\`\`
http://localhost:5000
\`\`\`

