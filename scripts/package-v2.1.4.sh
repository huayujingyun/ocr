- v2.1.2: Initial Windows deployment package

---

**Generated by Coze Coding Expert**
**Package Version: ${PACKAGE_VERSION}**
**Release Date: ${PACKAGE_DATE}**
EOF

echo ""
echo -e "${GREEN}Package structure created successfully!${NC}"

# Create tar.gz package
echo ""
echo "Creating tar.gz package..."
tar -czf ${PACKAGE_NAME}.tar.gz ${PACKAGE_NAME}

# Get file size
FILE_SIZE=$(du -h ${PACKAGE_NAME}.tar.gz | cut -f1)

echo ""
echo -e "${GREEN}========================================${NC}"
echo -e "${GREEN}  Package Created Successfully!${NC}"
echo -e "${GREEN}========================================${NC}"
echo ""
echo "Package Name: ${PACKAGE_NAME}.tar.gz"
echo "Package Size: ${FILE_SIZE}"
echo "Package Version: ${PACKAGE_VERSION}"
echo "Release Date: ${PACKAGE_DATE}"
echo ""
echo "Package Location: $(pwd)/${PACKAGE_NAME}.tar.gz"
echo ""
echo -e "${YELLOW}Next Steps:${NC}"
echo "1. Upload the package to object storage"
echo "2. Generate download link"
echo "3. Update documentation"
echo ""
